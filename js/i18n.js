export let lang = (() => {
  const saved = readStr(LS_LANG);
  if (saved && I18N[saved]) return saved;
  return /^fr/i.test(navigator.language || "") ? "fr" : "en";
})();

/** Translate a key; function entries receive the extra arguments. */
export function t(key, ...args) {
  const v = I18N[lang][key];
  if (typeof v === "function") return v(...args);
  return v === undefined ? key : v;
}

/** Date formatters for the current language (reassigned on language change). */
export const fmt = {};
function buildFormatters() {
  const L = I18N[lang].locale;
  fmt.long = new Intl.DateTimeFormat(L, { weekday: "long", day: "numeric", month: "long" });
  fmt.short = new Intl.DateTimeFormat(L, { weekday: "short", day: "numeric", month: "short" });
  fmt.time = new Intl.DateTimeFormat(L, { hour: "2-digit", minute: "2-digit" });
  fmt.dm = new Intl.DateTimeFormat(L, { day: "numeric", month: "numeric" });
  fmt.dayMon = new Intl.DateTimeFormat(L, { day: "numeric", month: "short" });
  fmt.monthYear = new Intl.DateTimeFormat(L, { month: "long", year: "numeric" });
  fmt.mon = new Intl.DateTimeFormat(L, { month: "short" });
}
buildFormatters();

/** Fill every element tagged with data-i18n / data-i18n-ph / data-i18n-aria. */
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach((e) => {
    e.textContent = t(e.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((e) => {
    e.placeholder = t(e.dataset.i18nPh);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((e) => {
    e.setAttribute("aria-label", t(e.dataset.i18nAria));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((e) => {
    e.title = t(e.dataset.i18nTitle);
  });
}

export function setLang(next) {
  if (!I18N[next] || next === lang) return;
  lang = next;
  writeStr(LS_LANG, next);
  buildFormatters();
  applyStatic();
  emit("lang");
}
